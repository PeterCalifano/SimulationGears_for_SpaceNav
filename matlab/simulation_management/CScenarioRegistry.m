    function [strSHgravityData, strSHmeta] = GetSphericalHarmonicsGravityData( ...
            enumOrName, ui32RequestedDegree, charLengthUnits)
        %% SIGNATURE
        % [strSHgravityData, strSHmeta] = GetSphericalHarmonicsGravityData( ...
        %     enumOrName, ui32RequestedDegree, charLengthUnits)
        % -------------------------------------------------------------------------------------------------------------
        %% DESCRIPTION
        % Resolve embedded spherical-harmonics gravity data for a registered
        % scenario. Each supported body owns one coefficient family; lower
        % requested degrees are exact prefixes of that family's triangular
        % [Clm, Slm] ordering.
        % -------------------------------------------------------------------------------------------------------------
        %% INPUT
        % enumOrName                 Scenario enum or registered scenario name.
        % ui32RequestedDegree        Maximum spherical-harmonics degree to return.
        % charLengthUnits            Output length units: "m" or "km".
        % -------------------------------------------------------------------------------------------------------------
        %% OUTPUT
        % strSHgravityData           Validated unnormalized coefficient rows and dimensional gravity data.
        % strSHmeta                  Provenance and registry metadata for the selected source.
        % -------------------------------------------------------------------------------------------------------------
        %% CHANGELOG
        % 24-07-2026  Pietro Califano, Codex     Document the single embedded-family contract.
        % -------------------------------------------------------------------------------------------------------------
        %% DEPENDENCIES
        % CScenarioRegistry.GetScenarioSpec
        % -------------------------------------------------------------------------------------------------------------

        arguments
            enumOrName (1,:) {mustBeA(enumOrName, ["string", "char", "EnumScenarioName"])}
            ui32RequestedDegree (1,1) uint32
            charLengthUnits {mustBeA(charLengthUnits, ["string", "char", "EnumLengthUnits"])} = "m"
        end

        charLengthUnits = EnumLengthUnits.toString(charLengthUnits);

        strSpec = CScenarioRegistry.GetScenarioSpec(enumOrName, charLengthUnits=charLengthUnits);
        strSHmeta = strSpec.strSphericalHarmonics;
        strSHgravityData = CScenarioRegistry.EmptySphericalHarmonicsGravityData_();

        % Reject unavailable degrees without silently selecting another source
        % or coefficient family.
        if ~strSHmeta.bHasHardcodedCoefficients || ui32RequestedDegree > strSHmeta.ui32HardcodedMaxDegree
            return
        end

        ui32RequiredRows = CScenarioRegistry.CountCoeffRows_(ui32RequestedDegree);
        strSHgravityData.dCSlmCoeffCols = strSHmeta.dCSlmCoeffCols(1:double(ui32RequiredRows), :);
        strSHgravityData.ui32MaxDegree = ui32RequestedDegree;
        strSHgravityData.dGravParam = strSHmeta.dGravParam;
        strSHgravityData.dBodyRadiusRef = strSHmeta.dBodyRadiusRef;
        strSHgravityData.dDensity = NaN;
        strSHgravityData.dGravConst = CScenarioRegistry.GetGravConstForLengthUnit_(charLengthUnits);
        strSHgravityData.strFitStats = struct( ...
            'charSource', strSHmeta.charSource, ...
            'charSourceUrl', strSHmeta.charSourceUrl, ...
            'charNormalization', strSHmeta.charNormalization, ...
            'charFieldKind', strSHmeta.charFieldKind, ...
            'ui32SourceMaxDegree', strSHmeta.ui32SourceMaxDegree, ...
            'ui32HardcodedMaxDegree', strSHmeta.ui32HardcodedMaxDegree, ...
            'bRegistryBacked', true);
        strSHgravityData.bRegistryBacked = true;
        strSHgravityData.strRegistryMetadata = strSHmeta;
    end

